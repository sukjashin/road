#!/usr/bin/env node
// 관측파일을 사이트 내장자료(road-observations.js)에 반영한다.
//
//   aws_1분/<관측 대상 이름>/<관측파일>.csv|.txt   ← 새 자료를 이렇게 넣고
//   node build-observations.cjs                     ← 실행하면 상세·회의용 화면 메뉴에 자동으로 생긴다
//
// 폴더 이름이 그대로 "관측 대상" 메뉴 이름이 된다 (예: 27번국도(곡성~고흥), 27번국도(곡성~고흥) 2026).
// 이미 내장된 자료는 그대로 두고, 같은 관측 대상·같은 파일명(확장자 제외)이면 새 파일로 교체한다.
//
//   node build-observations.cjs --list                 내장된 관측 대상 목록
//   node build-observations.cjs --remove "관측 대상"    해당 관측 대상 자료 삭제
//   node build-observations.cjs --dir <폴더>            aws_1분 대신 다른 폴더에서 읽기

const fs = require('fs');
const path = require('path');
const { detectObservationDate, groupObservationsByTarget } = require('./observation-targets.js');

const ROOT = __dirname;
const OUT_FILE = path.join(ROOT, 'road-observations.js');
const HEADER = '// Bundled historical observations. Generated by build-observations.cjs — 직접 고치지 말고 스크립트로 갱신하세요.\n';
const DATA_LINE = /^\d{4}-\d{2}-\d{2}\s+\d{1,2}:\d{2}/;

function readBundle(){
  if(!fs.existsSync(OUT_FILE)) return [];
  const s = fs.readFileSync(OUT_FILE, 'utf8');
  return JSON.parse(s.slice(s.indexOf('['), s.lastIndexOf(']') + 1));
}

function writeBundle(entries){
  entries.sort((a, b) => a.target.localeCompare(b.target, 'ko') || a.date.localeCompare(b.date) || a.name.localeCompare(b.name));
  const body = entries.map(e => JSON.stringify({ name: e.name, date: e.date, target: e.target, text: e.text })).join(',\n');
  const out = `${HEADER}const BUILTIN_OBSERVATIONS = [\n${body}\n];\n`;
  fs.writeFileSync(OUT_FILE, out, 'utf8');
  bumpScriptVersion(require('crypto').createHash('sha1').update(out).digest('hex').slice(0, 10));
}

// 브라우저가 예전 자료를 캐시해 메뉴가 갱신되지 않는 일이 없도록, 화면들의 <script src="road-observations.js?v=..."> 값을 내용 해시로 바꾼다
function bumpScriptVersion(hash){
  ['index.html', 'meeting.html'].forEach(name => {
    const file = path.join(ROOT, name);
    if(!fs.existsSync(file)) return;
    const html = fs.readFileSync(file, 'utf8');
    const next = html.replace(/road-observations\.js(\?v=[^"']*)?(["'])/g, `road-observations.js?v=${hash}$2`);
    if(next !== html) fs.writeFileSync(file, next, 'utf8');
  });
}

// 관측 장비 원본(txt)은 UTF-8, 엑셀에서 저장한 csv는 대개 EUC-KR(CP949)이다
function decode(buf){
  try { return new TextDecoder('utf-8', { fatal: true }).decode(buf); }
  catch { return new TextDecoder('euc-kr').decode(buf); }
}

// 결측 행('*')과 빈 줄을 빼고 머리말(#) + 관측 행만 남긴다
function clean(text){
  const lines = text.replace(/^﻿/, '').split(/\r?\n/).map(l => l.trim());
  const head = lines.find(l => l.startsWith('#'));
  const data = lines.filter(l => DATA_LINE.test(l));
  return { text: (head ? [head] : []).concat(data).join('\n'), rows: data.length };
}

const stem = name => name.replace(/\.[^.]+$/, '');
const keyOf = e => `${e.target}::${stem(e.name)}`;

function list(entries){
  const groups = groupObservationsByTarget(entries);
  if(!groups.length){ console.log('내장된 관측 자료가 없습니다.'); return; }
  groups.forEach(g => console.log(`- ${g.target} · ${g.period} · ${g.files.length}일 (${g.dates.join(', ')})`));
}

function main(){
  const args = process.argv.slice(2);
  const opt = name => { const i = args.indexOf(name); return i >= 0 ? (args[i + 1] || '') : null; };
  let entries = readBundle();

  if(args.includes('--list')){ list(entries); return; }

  const removeTarget = opt('--remove');
  if(removeTarget !== null){
    const before = entries.length;
    entries = entries.filter(e => e.target !== removeTarget);
    if(entries.length === before){
      console.error(`"${removeTarget}" 관측 대상을 찾지 못했습니다. --list로 이름을 확인하세요.`);
      process.exit(1);
    }
    writeBundle(entries);
    console.log(`"${removeTarget}" 자료 ${before - entries.length}개 파일을 삭제했습니다.`);
    list(entries);
    return;
  }

  const srcDir = path.resolve(ROOT, opt('--dir') || 'aws_1분');
  if(!fs.existsSync(srcDir)){
    console.error(`폴더가 없습니다: ${srcDir}`);
    process.exit(1);
  }

  const byKey = new Map(entries.map(e => [keyOf(e), e]));
  let added = 0, replaced = 0;
  const skipped = [];

  for(const dirent of fs.readdirSync(srcDir, { withFileTypes: true })){
    if(!dirent.isDirectory()) continue;
    const target = dirent.name.trim();
    const dir = path.join(srcDir, dirent.name);
    for(const file of fs.readdirSync(dir).filter(f => /\.(txt|csv)$/i.test(f)).sort()){
      const { text, rows } = clean(decode(fs.readFileSync(path.join(dir, file))));
      if(!rows){ skipped.push(`${target}/${file} (관측 행 없음)`); continue; }
      const entry = { name: file, date: detectObservationDate(file, text), target, text };
      if(byKey.has(keyOf(entry))) replaced++; else added++;
      byKey.set(keyOf(entry), entry);
    }
  }

  // 폴더 위치에 둔 .txt/.csv(관측 대상 폴더 없이)는 이름을 정할 수 없으므로 알려만 준다
  const loose = fs.readdirSync(srcDir).filter(f => /\.(txt|csv)$/i.test(f));
  loose.forEach(f => skipped.push(`${f} (관측 대상 폴더 안에 넣어주세요)`));

  writeBundle(Array.from(byKey.values()));
  console.log(`추가 ${added}개 · 교체 ${replaced}개 파일 반영 → ${path.basename(OUT_FILE)}`);
  if(skipped.length) console.log('건너뜀:\n  ' + skipped.join('\n  '));
  console.log('\n현재 관측 대상:');
  list(Array.from(byKey.values()));
}

main();
